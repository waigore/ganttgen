#!/usr/bin/env python3
"""Merge src/ganttgen modules into the committed single-file ganttgen.py.

Uses pymerger (dev dependency). On Python 3.14+, patches astunparse to use
stdlib ast.unparse because pymerger's bundled unparser is incompatible.
"""

from __future__ import annotations

import ast
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent
SRC = ROOT / "src" / "ganttgen"
OUT = ROOT / "ganttgen.py"

# Dependency order (leaf modules first). Exclude __init__/__main__.
MERGE_FILES = [
    SRC / "models.py",
    SRC / "calendar_util.py",
    SRC / "loading.py",
    SRC / "scheduling.py",
    SRC / "render.py",
    SRC / "cli.py",
]

HEADER = '''\
#!/usr/bin/env python3
"""Pure-stdlib Gantt chart generator for SP/program delivery plans.

Requires Python 3.14+. No third-party packages.

This file is generated by build.py from src/ganttgen/. Edit the modules, then
run:  python build.py
"""

'''

FOOTER = """
if __name__ == "__main__":
    raise SystemExit(main())
"""


def _patch_astunparse() -> None:
    """pymerger depends on astunparse, which breaks on Python 3.14 AST nodes."""
    import astunparse

    def _unparse(tree, *args, **kwargs):  # noqa: ANN001, ARG001
        return ast.unparse(tree) + "\n"

    astunparse.unparse = _unparse


def _patch_pymerger_main_block() -> None:
    """pymerger calls ast.If() with no args; that fails on Python 3.14+."""
    import astunparse
    import pymerger.merger as merger

    def get_main_block(nodes):  # noqa: ANN001
        removed_nodes = []
        main_block = ast.If(test=ast.Constant(value=False), body=[], orelse=[])
        found_test = False
        for node in nodes:
            if isinstance(node["node"], ast.If):
                if (
                    astunparse.unparse(node["node"].test).strip()
                    == "(__name__ == '__main__')"
                ):
                    if not found_test:
                        main_block.test = node["node"].test
                        found_test = True
                    removed_nodes.append(node)
                    main_block.body += node["node"].body
        for node in removed_nodes:
            nodes.remove(node)
        return main_block if len(main_block.body) > 0 else None

    merger.get_main_block = get_main_block


def build() -> Path:
    try:
        import pymerger
    except ImportError as exc:
        raise SystemExit(
            "pymerger is required to build. Install with:\n"
            "  pip install -r requirements-dev.txt"
        ) from exc

    _patch_astunparse()
    _patch_pymerger_main_block()

    missing = [p for p in MERGE_FILES if not p.is_file()]
    if missing:
        raise SystemExit(f"missing source files: {', '.join(str(p) for p in missing)}")

    paths = [str(p) for p in MERGE_FILES]
    merged = pymerger.merge(paths, output=None)
    if not merged or not merged.strip():
        raise SystemExit("pymerger produced empty output")

    # Drop any future/import noise already in HEADER; keep merged body as-is.
    body = merged.lstrip()
    if not body.startswith("from __future__"):
        # Ensure annotations future is present for the merged file.
        body = "from __future__ import annotations\n" + body

    text = HEADER + body
    if 'if __name__ == "__main__"' not in text:
        text = text.rstrip() + "\n" + FOOTER

    # Validate syntax before writing.
    try:
        compile(text, str(OUT), "exec")
    except SyntaxError as exc:
        raise SystemExit(f"merged output has syntax error: {exc}") from exc

    OUT.write_text(text, encoding="utf-8")
    print(f"Wrote {OUT} ({len(text)} bytes)")
    return OUT


if __name__ == "__main__":
    build()
    raise SystemExit(0)
